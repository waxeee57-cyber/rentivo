export type TranslationKey = keyof typeof translations.en

export function t(
  key: TranslationKey,
  lang: 'en' | 'es' | 'hu' = 'en',
  // `vars` is OPTIONAL on purpose: the ~1100 existing t(key, lang) call sites
  // must keep compiling unchanged. Only new strings carry {placeholder} tokens.
  vars?: Record<string, string | number>,
): string {
  const raw = (translations[lang] as Record<string, string>)[key]
    ?? (translations.en as Record<string, string>)[key]
    ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  )
}

/**
 * Plural-aware lookup using CLDR cardinal rules.
 *
 * Hungarian has no plural agreement after a numeral — it is "2 éjszaka",
 * never "2 éjszakák" — so `hu` always resolves to the "one" (singular-noun)
 * form. English and Spanish use the standard one/other split. The naive
 * `count === 1 ? 'night' : 'nights'` this replaces was wrong in two of the
 * three shipped languages.
 *
 * `count` is auto-exposed to the template as {count}.
 */
export function tPlural(
  keyOne: TranslationKey,
  keyOther: TranslationKey,
  count: number,
  lang: 'en' | 'es' | 'hu' = 'en',
  vars?: Record<string, string | number>,
): string {
  const key = lang === 'hu' || count === 1 ? keyOne : keyOther
  return t(key, lang, { count, ...vars })
}
